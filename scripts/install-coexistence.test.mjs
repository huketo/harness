import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, symlinkSync, unlinkSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const owner = readFileSync(join(repo, '.harness-owner'), 'utf8').trim();
const peerOwner = owner === 'huketo.harness-private' ? 'huketo.harness-public' : 'huketo.harness-private';
const skill = readdirSync(join(repo, 'skills'), {withFileTypes:true}).find(e => e.isDirectory() && !e.name.startsWith('bstack')).name;
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), 'harness-coexist-'));
  t.after(() => rmSync(root, {recursive:true,force:true}));
  const home = join(root, 'home');
  mkdirSync(join(home,'.claude'), {recursive:true});
  writeFileSync(join(home,'.claude','CLAUDE.md'), 'User-owned rules.');
  const run = (...args) => spawnSync('bash', [join(repo,'install.sh'), ...args], {env:{...process.env,HOME:home},encoding:'utf8'});
  let first = run();
  assert.equal(first.status,0,first.stderr);
  const peer = join(root,'peer');
  mkdirSync(join(peer,'skills',skill), {recursive:true});
  mkdirSync(join(peer,'omp'), {recursive:true});
  writeFileSync(join(peer,'.harness-owner'), peerOwner+'\n');
  writeFileSync(join(peer,'skills',skill,'SKILL.md'), 'Peer canonical skill.');
  writeFileSync(join(peer,'omp','profiles.ts'), 'Peer canonical profile.');
  return {root,home,peer,run};
}
test('known peer ownership converges without duplicate skill discovery or replacing higher priority assets', t => {
  const {home,peer,run} = fixture(t);
  const target = join(home,'.agents','skills',skill);
  const profile = join(home,'.local','bin','omp-profile');
  unlinkSync(target); symlinkSync(join(peer,'skills',skill),target);
  unlinkSync(profile); symlinkSync(join(peer,'omp','profiles.ts'),profile);
  const applied = run();
  assert.equal(applied.status,0,applied.stderr);
  const preferred = owner === 'huketo.harness-private' ? repo : peer;
  assert.equal(realpathSync(target),join(preferred,'skills',skill));
  assert.equal(realpathSync(join(home,'.claude','skills',skill)),join(preferred,'skills',skill));
  assert.equal(realpathSync(profile),join(preferred,'omp','profiles.ts'));
  const again = run();
  assert.equal(again.status,0,again.stderr);
  assert.equal(realpathSync(target),join(preferred,'skills',skill));
  const dry = run('--dry-run');
  assert.equal(dry.status,0,dry.stderr);
  assert.equal(realpathSync(profile),join(preferred,'omp','profiles.ts'));
});
test('foreign links remain a conflict and user files plus bstack namespace survive', t => {
  const {root,home,run} = fixture(t);
  const target = join(home,'.agents','skills',skill);
  const foreign = join(root,'thirdparty');
  mkdirSync(foreign); writeFileSync(join(foreign,'SKILL.md'),'Unrelated content.');
  unlinkSync(target); symlinkSync(foreign,target);
  const bstack = join(root,'bstack-review');
  mkdirSync(bstack); writeFileSync(join(bstack,'SKILL.md'),'Team process.');
  const teamTarget = join(home,'.agents','skills','bstack-review'); symlinkSync(bstack,teamTarget);
  const blocked = run();
  assert.notEqual(blocked.status,0);
  assert.equal(realpathSync(target),foreign);
  assert.equal(realpathSync(teamTarget),bstack);
  assert.equal(readFileSync(join(home,'.claude','CLAUDE.md'),'utf8'),'User-owned rules.');
});
