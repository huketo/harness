"""Fetch, verify, and subset the deck's pinned Korean fonts.

  uv run tools/fonts.py fetch                  # fonts/full/, fonts/fonts.css, fonts/LICENSES.txt
  uv run tools/fonts.py subset --text FILE     # fonts/subset/ with only FILE's characters

Every downloaded byte is checked against tools/fonts.json before use. Subset
files are modified versions under OFL-1.1, so their internal names become the
role name ("Deck Sans", ...) and never keep a Reserved Font Name.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
import urllib.request
import zipfile
from pathlib import Path

from fontTools import subset as ftsubset
from fontTools.ttLib import TTFont

DECK = Path(__file__).resolve().parent.parent
MANIFEST = DECK / "tools" / "fonts.json"
CACHE = DECK / ".font-cache"
FULL = DECK / "fonts" / "full"
SUBSET = DECK / "fonts" / "subset"
ROLE_FAMILY = {"sans": "Deck Sans", "serif": "Deck Serif", "display": "Deck Display", "mono": "Deck Mono"}


def fail(msg: str) -> None:
    sys.exit(f"fonts.py: {msg}")


def download(url: str, sha256: str) -> bytes:
    """Return the verified bytes for url, reusing .font-cache/ when it already holds them."""
    CACHE.mkdir(exist_ok=True)
    cached = CACHE / sha256
    if cached.exists() and hashlib.sha256(cached.read_bytes()).hexdigest() == sha256:
        return cached.read_bytes()
    req = urllib.request.Request(url, headers={"User-Agent": "awesome-slides-fonts"})
    with urllib.request.urlopen(req, timeout=120) as res:
        data = res.read()
    got = hashlib.sha256(data).hexdigest()
    if got != sha256:
        fail(f"sha256 mismatch for {url}: expected {sha256}, got {got}")
    cached.write_bytes(data)
    return data


def file_bytes(entry: dict) -> bytes:
    if "archive" in entry:
        archive = download(entry["archive"]["url"], entry["archive"]["sha256"])
        data = zipfile.ZipFile(io.BytesIO(archive)).read(entry["member"])
        got = hashlib.sha256(data).hexdigest()
        if got != entry["sha256"]:
            fail(f"sha256 mismatch for {entry['member']}: expected {entry['sha256']}, got {got}")
        return data
    return download(entry["url"], entry["sha256"])


def weight_slug(weight) -> str:
    return "var" if isinstance(weight, str) else str(weight)


def selected(manifest: dict):
    """Yield (role, family_id, family) for every role in `use`."""
    for role, family_id in manifest["use"].items():
        if role not in ROLE_FAMILY:
            fail(f"unknown role {role!r} in use; expected one of {sorted(ROLE_FAMILY)}")
        family = manifest["families"].get(family_id)
        if family is None:
            fail(f"use.{role} names {family_id!r}, which is not in families")
        if role not in family["roles"]:
            fail(f"{family_id} is not listed for role {role}; see FONTS.md")
        yield role, family_id, family


def fetch(manifest: dict) -> None:
    FULL.mkdir(parents=True, exist_ok=True)
    css, notices = [], []
    for role, family_id, family in selected(manifest):
        for entry in family["files"]:
            font = TTFont(io.BytesIO(file_bytes(entry)))
            font.flavor = "woff2"  # compression only; names stay as published
            name = f"{role}-{weight_slug(entry['weight'])}.woff2"
            font.save(FULL / name)
            css.append(
                "@font-face {\n"
                f"  font-family: '{ROLE_FAMILY[role]}';\n"
                f"  src: url('@deckfont/{name}') format('woff2');\n"
                f"  font-weight: {entry['weight']};\n"
                "  font-style: normal;\n"
                "  font-display: block;\n"
                "}\n"
            )
        lic = download(family["license"]["url"], family["license"]["sha256"]).decode("utf-8")
        notices.append(f"== {ROLE_FAMILY[role]}: {family_id} {family['version']} ({family['license']['url']})\n{lic.strip()}\n")
    header = "/* Generated by tools/fonts.py from tools/fonts.json. Edit `use` there, then rerun `npm run fonts`. */\n"
    (DECK / "fonts" / "fonts.css").write_text(header + "\n".join(css), encoding="utf-8")
    (DECK / "fonts" / "LICENSES.txt").write_text("\n".join(notices), encoding="utf-8")
    print(f"fonts.py: wrote {len(css)} faces to {FULL.relative_to(DECK)}/ and fonts/fonts.css")


def rename(font: TTFont, family: str, reserved: list[str]) -> None:
    """Give a subset (a Modified Version under OFL) a name free of any Reserved Font Name."""
    names = font["name"]
    style = names.getDebugName(17) or names.getDebugName(2) or "Regular"
    ps = f"{family.replace(' ', '')}-{style.replace(' ', '')}"
    # Name records exist per platform and language (a Korean family name, a Mac
    # name); drop every naming record, then write the role name once.
    for nid in (1, 2, 3, 4, 6, 16, 17, 18, 21, 22):
        names.removeNames(nameID=nid)
    names.setName(family, 1, 3, 1, 0x409)
    names.setName(style, 2, 3, 1, 0x409)
    names.setName(f"{ps};subset", 3, 3, 1, 0x409)
    names.setName(f"{family} {style}", 4, 3, 1, 0x409)
    names.setName(ps, 6, 3, 1, 0x409)
    if "CFF " in font:
        font["CFF "].cff.fontNames = [ps]
    # The RFN restriction covers names users see as the font's name; copyright,
    # designer, and license records keep crediting the original.
    naming = {1, 2, 3, 4, 5, 6, 16, 17, 18, 21, 22, 25}
    kept = [r for r in names.names if (r.nameID in naming or r.nameID >= 256) and any(n.lower() in str(r).lower() for n in reserved)]
    if kept:
        fail(f"{family}: Reserved Font Name still present in name IDs {sorted({r.nameID for r in kept})}")


def make_subset(manifest: dict, text_file: Path) -> None:
    text = text_file.read_text(encoding="utf-8")
    SUBSET.mkdir(parents=True, exist_ok=True)
    options = ftsubset.Options()
    options.layout_features = ["*"]
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    for role, family_id, family in selected(manifest):
        for entry in family["files"]:
            name = f"{role}-{weight_slug(entry['weight'])}.woff2"
            source = FULL / name
            if not source.exists():
                fail(f"{source.relative_to(DECK)} is missing; run `npm run fonts` first")
            font = TTFont(source)
            sub = ftsubset.Subsetter(options)
            sub.populate(text=text)
            sub.subset(font)
            rename(font, ROLE_FAMILY[role], family.get("rfn", []))
            font.flavor = "woff2"
            font.save(SUBSET / name)
            print(f"fonts.py: {name} {source.stat().st_size // 1024} KB -> {(SUBSET / name).stat().st_size // 1024} KB")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    cmd = parser.add_subparsers(dest="cmd", required=True)
    cmd.add_parser("fetch", help="download, verify, and write the full fonts")
    sp = cmd.add_parser("subset", help="write fonts/subset/ limited to the characters in --text")
    sp.add_argument("--text", type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if args.cmd == "fetch":
        fetch(manifest)
    else:
        make_subset(manifest, args.text)


if __name__ == "__main__":
    main()
